"""Curated metric keys.

Slot ids from ``src/metrics/registry.ts`` are included so a later API can fill
the page without inventing new names. Extra keys cover the national measures
the page header and the draft composite need: population, stop counts, overlay
shares, amenity counts, and distances to essential services.

``formula_group_id`` is the draft input mapping. A group may have more than
one metric. The scorer applies that group's ceiling once. It must not add the
ceiling again for every metric. Housing is stored and can be ranked, and it
is not an input of the draft composite in ``contracts/formula.json``.

Direction describes the measure. ``positive`` means a larger number is a
better reading. ``negative`` means a larger number is a worse reading
(an offence rate, an overlay share, a distance). ``context`` is descriptive.
A distance can be ``negative`` while the formula group that uses it is
``positive``: access points are awarded for being close, and the scorer
inverts the distance. This module does not do that arithmetic.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class MetricDef:
    metric_key: str
    label: str
    section_id: str
    group_id: str | None
    unit: str | None
    direction: str
    value_kind: str
    formula_group_id: str | None
    map_metric: bool
    description: str


def _m(
    key: str,
    label: str,
    section: str,
    group: str | None,
    unit: str | None,
    direction: str,
    description: str,
    *,
    kind: str = "numeric",
    formula: str | None = None,
    map_metric: bool = False,
) -> MetricDef:
    return MetricDef(
        metric_key=key,
        label=label,
        section_id=section,
        group_id=group,
        unit=unit,
        direction=direction,
        value_kind=kind,
        formula_group_id=formula,
        map_metric=map_metric,
        description=description,
    )


def metric_definitions() -> tuple[MetricDef, ...]:
    return _METRICS


